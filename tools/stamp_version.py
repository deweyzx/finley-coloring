"""
stamp_version.py - gives every app file reference a version stamp, e.g. "editor.js?v=202610181405".

Why: GitHub Pages lets browsers keep a copy of each file for about 10 minutes. Right after an
update, Safari could run the NEW page with some OLD code files (it already had them), and
things half-work. With a fresh stamp in every reference, the new page asks for files by
names the browser has never seen, so it always gets the matching new code. An old cached page
keeps asking for the old names, so it runs the complete old version until it refreshes.

Run it before every upload:   python tools/stamp_version.py
It updates index.html and the import lines in js/*.js. (Claude runs this when committing.)
"""

import datetime
import glob
import os
import re
import hashlib
import json
from pathlib import Path

PROJECT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VERSION = datetime.datetime.now().strftime("%Y%m%d%H%M%S")

# import ... from "./editor.js"  /  from "../pages/pages.js"   (with or without an old ?v=)
IMPORTS = re.compile(r"""(\bfrom\s+["'])(\.{1,2}/[^"'?]+\.js)(\?v=[^"']*)?(["'])""")
# new Worker("js/fill-worker.js")
WORKERS = re.compile(r"""(new\s+Worker\(\s*["'])([^"'?]+\.js)(\?v=[^"']*)?(["'])""")
# <link href="css/styles.css">  /  <script src="js/app.js">
HTML_REFS = re.compile(r"""((?:href|src)=")((?:css|js)/[^"?]+\.(?:css|js))(\?v=[^"]*)?(")""")


def stamp(path, patterns):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    new = text
    for pattern in patterns:
        new = pattern.sub(lambda m: f"{m.group(1)}{m.group(2)}?v={VERSION}{m.group(4)}", new)
    if new != text:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(new)
        return True
    return False


changed = []
if stamp(os.path.join(PROJECT, "index.html"), [HTML_REFS]):
    changed.append("index.html")
for path in sorted(glob.glob(os.path.join(PROJECT, "js", "*.js"))):
    if stamp(path, [IMPORTS, WORKERS]):
        changed.append(os.path.relpath(path, PROJECT).replace("\\", "/"))

# The worker's version must match its contents list. It verifies every small app file
# before accepting an update, so a half-deployed GitHub upload keeps the old app working.
root = Path(PROJECT)
worker = root / "sw.js"
text = worker.read_text(encoding="utf-8")
text = re.sub(r'const VERSION = "[^"]+";', f'const VERSION = "{VERSION}";', text)
text = re.sub(r'importScripts\("\./offline-assets\.js\?v=[^"]+"\);', f'importScripts("./offline-assets.js?v={VERSION}");', text)
worker.write_text(text, encoding="utf-8", newline="\n")

def asset(path, versioned=False):
    relative = path.relative_to(root).as_posix()
    content = path.read_bytes()
    # Git on Windows may check out CRLF while GitHub serves LF. Both represent the
    # same text; verify a consistent line-ending form instead of rejecting a good upload.
    if path.suffix.lower() in (".html", ".css", ".js", ".svg", ".webmanifest", ".txt"):
        content = content.replace(b"\r\n", b"\n")
    return {"url": relative + (f"?v={VERSION}" if versioned else ""),
            "hash": hashlib.sha256(content).hexdigest()}

shell = [asset(root / "index.html"), asset(root / "manifest.webmanifest")]
shell += [asset(p, True) for p in sorted((root / "js").glob("*.js"))]
shell += [asset(p, True) for p in sorted((root / "css").glob("*.css"))]
shell += [asset(root / "pages/pages.js", True)]
shell += [asset(root / "icons" / name) for name in ("apple-touch-icon.png", "icon-192.png", "icon-512.png")]
shell += [asset(p) for p in sorted((root / "fonts").rglob("*.woff2"))]
shell += [asset(p) for p in sorted((root / "fonts").glob("*-OFL.txt"))]
shell += [asset(p) for p in sorted((root / "thumbs").rglob("*.png"))]
shell += [asset(p) for p in sorted((root / "pages").rglob("*.svg"))]
pages = [asset(p) for p in sorted((root / "pages").rglob("*"))
         if p.is_file() and p.suffix.lower() in (".png", ".jpg", ".jpeg", ".webp", ".svg")]
data = {"version": VERSION, "shell": shell, "pages": pages}
(root / "offline-assets.js").write_text(
    "// Generated by tools/stamp_version.py. Run it after changing app files or importing pages.\n"
    + "self.FINLEY_OFFLINE = " + json.dumps(data, indent=2) + ";\n", encoding="utf-8", newline="\n")
print(f"Version {VERSION}: stamped {len(changed)} file(s): {', '.join(changed)}")
print(f"Offline contents: {len(shell)} app/thumbnail files, {len(pages)} downloadable outlines.")
